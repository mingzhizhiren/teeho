MAX_TEXT_LENGTH = 8000
CONTROL_CHARACTERS = re.compile(r"[\x00-\x1f\x7f-\x9f\u202a-\u202e\u2066-\u2069]")
SENSITIVE_QUERY_KEY = re.compile(r"token|signature|credential|secret", re.IGNORECASE)


def safe_text(value: object) -> str:
    """用户文字不能跳出代码块、插入控制序列。"""
    if not isinstance(value, str):
        return ""
    normalized = unicodedata.normalize("NFC", value)
    cleaned = CONTROL_CHARACTERS.sub(" ", normalized).replace("`", "ˋ")
    return re.sub(r"\s+", " ", cleaned).strip()[:MAX_TEXT_LENGTH]


def safe_url(value: object, allow_platform_access: bool = False) -> Optional[str]:
    """只展示无凭据、无敏感查询参数的 HTTP(S) 地址。"""
    if not isinstance(value, str) or CONTROL_CHARACTERS.search(value):
        return None
    try:
        parts = urlsplit(value)
        if parts.scheme not in ("http", "https") or not parts.hostname:
            return None
        if parts.username is not None or parts.password is not None:
            return None
        platform = any(parts.hostname == host or parts.hostname.endswith("." + host)
                       for host in ("xiaohongshu.com", "xhslink.com", "rednote.com"))
        if any(SENSITIVE_QUERY_KEY.search(key)
               and not (allow_platform_access and platform and key == "xsec_token")
               for key, _ in parse_qsl(parts.query)):
            return None
        host = parts.hostname.encode("idna").decode("ascii").lower()
        if any(character in host for character in (" ", "\\", "%")):
            return None
        host = "[" + host + "]" if ":" in host else host
        port = parts.port
        authority = (
            host if port in (None, 80 if parts.scheme == "http" else 443) else f"{host}:{port}"
        )
        path = quote(parts.path or "/", safe="/%:@!$&'()*+,;=-._~")
        query = quote(parts.query, safe="%/?@!$&'()*+,;=:-._~")
        fragment = quote(parts.fragment, safe="%/?@!$&'()*+,;=:-._~")
        return urlunsplit((parts.scheme, authority, path, query, fragment))
    except (ValueError, UnicodeError):
        return None


